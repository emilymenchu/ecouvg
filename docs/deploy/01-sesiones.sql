-- Adaptado del esquema PostgreSQL de Spring Session JDBC.
-- No contiene cambios a las tablas de negocio ni se ejecuta al arrancar.
BEGIN;
CREATE SCHEMA ecouvg_private;

CREATE TABLE ecouvg_private.spring_session (
    PRIMARY_ID CHAR(36) NOT NULL,
    SESSION_ID CHAR(36) NOT NULL,
    CREATION_TIME BIGINT NOT NULL,
    LAST_ACCESS_TIME BIGINT NOT NULL,
    MAX_INACTIVE_INTERVAL INT NOT NULL,
    EXPIRY_TIME BIGINT NOT NULL,
    PRINCIPAL_NAME VARCHAR(100),
    CONSTRAINT SPRING_SESSION_PK PRIMARY KEY (PRIMARY_ID)
);
CREATE UNIQUE INDEX SPRING_SESSION_IX1 ON ecouvg_private.spring_session (SESSION_ID);
CREATE INDEX SPRING_SESSION_IX2 ON ecouvg_private.spring_session (EXPIRY_TIME);
CREATE INDEX SPRING_SESSION_IX3 ON ecouvg_private.spring_session (PRINCIPAL_NAME);

CREATE TABLE ecouvg_private.spring_session_attributes (
    SESSION_PRIMARY_ID CHAR(36) NOT NULL,
    ATTRIBUTE_NAME VARCHAR(200) NOT NULL,
    ATTRIBUTE_BYTES BYTEA NOT NULL,
    CONSTRAINT SPRING_SESSION_ATTRIBUTES_PK PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
    CONSTRAINT SPRING_SESSION_ATTRIBUTES_FK FOREIGN KEY (SESSION_PRIMARY_ID)
        REFERENCES ecouvg_private.spring_session(PRIMARY_ID) ON DELETE CASCADE
);
COMMIT;
